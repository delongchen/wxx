const fsp = require('node:fs/promises')

const fetchOpenApiJson = () => {
    const url = 'https://www.mingweisamuel.com/riotapi-schema/openapi-3.0.0.json'

    return fetch(url)
        .then(res => res.json())
        .catch(err => {
            console.log(err)
            return {}
        })
}

const getRefType = (ref) => {
    return ref.split('.').pop()
}

const fmtType = (body) => {
    const type = body.type

    if (type === undefined) {
        const ref = body['$ref']
        if (ref === undefined) return 'unknown'
        return getRefType(ref)
    }

    if (type === 'array') {
        if (body.items === undefined) {
            return 'unknown[]'
        }

        return fmtType(body.items) + '[]'
    }

    if (type === 'integer') {
        return 'number'
    }

    if (type === 'boolean') {
        return 'boolean'
    }

    if (type === 'string') {
        const enumItem = body['enum']
        if (Array.isArray(enumItem) && enumItem.length !== 0) {
            return '(' +
                enumItem
                    .map(it => `"${it}"`)
                    .join(' | ')
            + ')'
        }

        return 'string'
    }

    if (type === 'object') {
        return 'any'
    }

    return 'unknown'
}

const parseProperty = (name, body, required) => {
    const desc = body.description
    const type = fmtType(body)

    return {
        name,
        desc,
        type,
        required,
    }
}

const parseProperties = (properties, required) => {
    return Object.entries(properties)
        .map(([name, body]) => {
            return parseProperty(name, body, required.has(name))
        })
}

const parseSchema = (key, schema) => {
    const namePath = key.split('.')
    const namespace = namePath.length === 1 ? 'common' : namePath[0]
    const name = schema.title ?? key
    const desc = schema.description
    const required = new Set(schema.required ?? [])
    const properties = parseProperties(schema.properties ?? {}, required)

    return {
        name,
        namespace,
        desc,
        properties,
    }
}

const fmtComment = (comment, level = 0) => {
    return '\n' + comment
        .split('\n')
        .map(line => `${'  '.repeat(level)}// ${line}`)
        .join('\n') + '\n'
}

const renderTS = (schema) => {
    const comment = schema.desc ? fmtComment(schema.desc) : ''
    const def =
`export interface ${schema.name} {
${schema.properties.map(property => {
        const text = `  ${property.name}${property.required ? ':' : '?:'} ${property.type},`
        const desc = property.desc
        if (desc !== undefined) {
            return fmtComment(desc, 1) + text
        }
        return text
    }).join('\n')}
}`
    return comment + def
}

const main = async () => {
    const outputDir = '../guest-js/types/riot-api-dto'
    const schemaMap = new Map

    for (const [key, body] of Object.entries(await fetchOpenApiJson())) {
        const parsed = parseSchema(key, body)
        const exist = schemaMap.get(parsed.namespace)
        if (exist === undefined) {
            schemaMap.set(parsed.namespace, [parsed])
        } else {
            exist.push(parsed)
        }
    }

    for (const [namespace, schemas] of schemaMap.entries()) {
        const comment = `// This file is automatically generated, please do not modify it.\n\n\n`

        await fsp.writeFile(
            [outputDir, `${namespace}.d.ts`].join('/'),
            comment + schemas.map(renderTS).join('\n\n')
        )
    }
}

main().catch(console.error)
